def resolve_single_indic_compound_word(word: str) -> Optional[int]:
    """Resolve a single Indic word that may be a direct entry or fused stem+unit (0-999)."""
    low = word.lower()
    if low in MULTILINGUAL_NUMBER_WORDS:
        return MULTILINGUAL_NUMBER_WORDS[low]

    for stem, val in HUNDRED_PREFIX_STEMS:
        if low == stem:
            return val
        if low.startswith(stem):
            rem = low[len(stem) :]
            if rem in MULTILINGUAL_NUMBER_WORDS:
                return val + MULTILINGUAL_NUMBER_WORDS[rem]
            if rem in FUSED_UNIT_SUFFIXES:
                return val + FUSED_UNIT_SUFFIXES[rem]

    for stem, val in TENS_STEMS:
        if low == stem:
            return val
        if low.startswith(stem):
            rem = low[len(stem) :]
            if rem in MULTILINGUAL_NUMBER_WORDS:
                return val + MULTILINGUAL_NUMBER_WORDS[rem]
            if rem in FUSED_UNIT_SUFFIXES:
                return val + FUSED_UNIT_SUFFIXES[rem]

    return None


